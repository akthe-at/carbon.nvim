-- nvim --headless -u NONE -l scripts/ghostty.lua [--check]
vim.opt.rtp:prepend(vim.fn.getcwd())
local check = vim.tbl_contains(arg, '--check')
for _, style in ipairs({'carbon', 'carbon_day', 'carbon_contrast', 'carbon_day_neutral', 'carbon_day_contrast'}) do
  local c = require('carbon.palette').setup({style = style})
  require('carbon').terminal(c)
  local lines = {'# Generated by scripts/ghostty.lua; edit lua/carbon/palette.lua instead.'}
  for _, pair in ipairs({{'background', c.bg}, {'foreground', c.fg}, {'cursor-color', c.cursor},
    {'selection-background', c.selection}, {'selection-foreground', c.fg}}) do
    lines[#lines + 1] = pair[1] .. ' = ' .. pair[2]
  end
  for i = 0, 15 do lines[#lines + 1] = 'palette = ' .. i .. '=' .. vim.g['terminal_color_' .. i] end
  local path = 'extras/ghostty/' .. style:gsub('_', '-')
  if check then
    assert(vim.deep_equal(lines, vim.fn.readfile(path)), path .. ' is stale')
  else vim.fn.writefile(lines, path) end
end
print('Ghostty palettes verified')
vim.cmd('qa!')
