-- Generate standalone Vim colorschemes from Carbon's shared Lua palettes.
-- Run: nvim --headless -u NONE -l scripts/vim-colors.lua
vim.opt.rtp:prepend(vim.fn.getcwd())

local palette = require('carbon.palette')
local roles = {
  Comment = {'comment', '', 'italic'}, Constant = {'constant', '', '', 'variable'},
  String = {'string'}, Character = {'string'}, Number = {'number'}, Boolean = {'keyword'},
  Float = {'number'}, Identifier = {'variable'}, Function = {'func'}, Statement = {'keyword'},
  Conditional = {'keyword'}, Repeat = {'keyword'}, Label = {'keyword'}, Operator = {'bracket'},
  Keyword = {'keyword'}, Exception = {'keyword'}, PreProc = {'keyword'}, Include = {'keyword'},
  Define = {'keyword'}, Macro = {'func'}, PreCondit = {'keyword'}, Type = {'class'},
  StorageClass = {'keyword'}, Structure = {'class'}, Typedef = {'class'}, Special = {'identifier'},
  SpecialChar = {'string'}, Tag = {'html_tag'}, Delimiter = {'bracket'},
  SpecialComment = {'comment', '', 'italic'}, Debug = {'error'}, Underlined = {'link', '', 'underline'},
  Error = {'error'},
}
local ui = {
  Normal = {'fg','bg'}, NormalFloat = {'fg','float_bg'}, CursorLine = {'','cursor_line_bg'},
  CursorLineNr = {'cursor_line_fg','cursor_line_bg'}, LineNr = {'line_nr','gutter'},
  SignColumn = {'link','gutter'}, VertSplit = {'border','bg'}, WinSeparator = {'border','bg'},
  StatusLine = {'fg','panel_bg'}, StatusLineNC = {'comment','panel_bg'},
  TabLine = {'comment','panel_bg'}, TabLineFill = {'','panel_bg'}, TabLineSel = {'fg','bg','bold'},
  Pmenu = {'pmenu_fg','pmenu_bg'}, PmenuSel = {'pmenu_sel_fg','pmenu_sel_bg','bold'},
  PmenuSbar = {'','pmenu_bg'}, PmenuThumb = {'','border'}, Visual = {'','selection'},
  Search = {'bg','search'}, IncSearch = {'bg','search','bold,underline'},
  MatchParen = {'fg','match_bg','bold'}, Folded = {'comment','panel_bg'}, NonText = {'comment'},
  SpecialKey = {'comment'}, Directory = {'link'}, Title = {'class','', 'bold'}, Conceal = {'comment'},
  QuickFixLine = {'','panel_bg','bold'}, WildMenu = {'bg','search'}, ColorColumn = {'','panel_bg'},
  ModeMsg = {'fg','', 'bold'}, MoreMsg = {'info'}, Question = {'info'}, ErrorMsg = {'error','bg','bold'},
  WarningMsg = {'warning'}, DiffAdd = {'','diff_add_bg'}, DiffDelete = {'','diff_remove_bg'},
  DiffChange = {'','diff_change_bg'}, DiffText = {'diff_change','diff_change_bg','bold'},
  Todo = {'bg','warning','bold'}, SpellBad = {'','', 'undercurl'}, SpellCap = {'','', 'undercurl'},
  SpellLocal = {'','', 'undercurl'}, SpellRare = {'','', 'undercurl'},
}
local styles = {'carbon','carbon_day','carbon_contrast','carbon_day_neutral','carbon_day_contrast'}
local names = {carbon='carbon', carbon_day='carbon-day', carbon_contrast='carbon-contrast',
  carbon_day_neutral='carbon-day-neutral', carbon_day_contrast='carbon-day-contrast'}
local function hi(group, spec, c)
  local fg = spec[1] ~= '' and c[spec[1]] or nil
  if not fg and spec[4] then fg = c[spec[4]] end
  local bg = spec[2] ~= '' and c[spec[2]] or nil
  local attr = spec[3]
  local fields = {}
  if fg then fields[#fields+1] = 'guifg=' .. fg end
  if bg then fields[#fields+1] = 'guibg=' .. bg end
  if attr and attr ~= '' then fields[#fields+1] = 'gui=' .. attr end
  return 'hi ' .. group .. ' ' .. table.concat(fields, ' ')
end
for _, style in ipairs(styles) do
  local c = palette.setup({style=style})
  local lines = {'" Generated by scripts/vim-colors.lua; edit lua/carbon/palette.lua instead.',
    'set background=' .. (style:find('day') and 'light' or 'dark'), 'hi clear',
    'if exists("syntax_on") | syntax reset | endif', 'let g:colors_name = "' .. names[style] .. '"',
    'if !has("gui_running") && &t_Co < 256 | finish | endif', ''}
  for group, spec in pairs(ui) do lines[#lines+1] = hi(group, spec, c) end
  lines[#lines+1] = ''
  for group, spec in pairs(roles) do lines[#lines+1] = hi(group, spec, c) end
  for _, group in ipairs({'markdownCode','markdownCodeBlock'}) do lines[#lines+1] = hi(group, {'string'}, c) end
  lines[#lines+1] = ''
  local path = 'extras/vim/' .. names[style] .. '.vim'
  vim.fn.mkdir(vim.fn.fnamemodify(path, ':h'), 'p')
  vim.fn.writefile(lines, path)
end
print('Generated standalone Vim colorschemes from Carbon palettes')
